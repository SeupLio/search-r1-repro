def parse_seed_items() -> list[dict]:
    items = []
    for line in _SEED_TSV.strip().splitlines():
        parts = [p.strip() for p in line.split("|")]
        (doc_id, platform, topic, title, author, date,
         views, likes, collects, comments, shares, duration, note) = parts
        items.append({
            "id": doc_id,
            "platform": platform,
            "platform_cn": PLATFORM_CN[platform],
            "topic": topic,
            "title": title,
            "author": author,
            "publish_date": date,
            "views": int(views),
            "likes": int(likes),
            "collects": int(collects),
            "comments": int(comments),
            "shares": int(shares),
            "duration_sec": int(duration),
            "note": note,
        })
    return items


